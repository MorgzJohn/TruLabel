def resolve_curated_image(item: dict) -> str:
    raw_img = item.get("image_url", "")
    if raw_img:
        # Check if raw_img is a blacklisted dish photo
        if any(bad in raw_img for bad in DISH_PHOTO_BLACKLIST):
            raw_img = ""
        else:
            return raw_img
    text = (item.get("name", "") + " " + item.get("categories", "") + " " + item.get("brand", "")).lower()
    for kw, url in CATEGORY_IMAGE_MAP.items():
        if kw in text:
            return url
    return raw_img or ""


