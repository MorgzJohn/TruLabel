def _normalize_str(s: str) -> str:
    return re.sub(r"[-—|:;,/()]+", " ", s.lower()).strip()


def find_curated_product(query: str, country: str = "india") -> dict | None:
    """
    Searches the curated Indian FMCG & supplements database for a matching product.
    Supports fuzzy name, brand, and keyword matches.
    """
    if not query or not query.strip():
        return None

    clean_q = _normalize_str(query)
    q_tokens = clean_q.split()

    # Pass 1: Exact keyword / ID match
    for item in CURATED_FOOD_DATABASE:
        if clean_q == item["id"] or clean_q == item["name"].lower():
            return _format_curated_evidence(item, country=country)
        if any(clean_q == kw.lower() for kw in item.get("keywords", [])):
            return _format_curated_evidence(item, country=country)

    # Pass 2: Substring or high token overlap
    best_item = None
    best_score = 0.0

    for item in CURATED_FOOD_DATABASE:
        item_text = f"{item['brand']} {item['name']} {' '.join(item.get('keywords', []))}".lower()
        matched_tokens = sum(1 for t in q_tokens if t in item_text)
        token_ratio = matched_tokens / len(q_tokens) if q_tokens else 0

        seq_ratio = difflib.SequenceMatcher(None, clean_q, item["name"].lower()).ratio()
        score = (token_ratio * 0.7) + (seq_ratio * 0.3)

        if score > best_score and score >= 0.50:
            best_score = score
            best_item = item

    if best_item:
        return _format_curated_evidence(best_item, country=country)

    return None


def search_curated_category(category_domain: str, query: str = "", country: str = "india") -> list[dict]:
    """
    Searches the curated database for products matching a category domain or search query.
    """
    results = []
    clean_q = _normalize_str(f"{category_domain} {query}")
    terms = clean_q.split()

    for item in CURATED_FOOD_DATABASE:
        item_cat = f"{item['categories']} {' '.join(item.get('keywords', []))}".lower()
        if any(term in item_cat for term in terms):
            results.append(_format_curated_evidence(item, country=country))

    return results



